std::shared_ptr<BasisManager::Basis> BasisManager::generateDirectLinkAlongPath(const std::vector<std::shared_ptr<Basis> > &path)
{
    assert(path.size() > 2);// If it is a one it is already a direct link and this should not be called
    //Path should contain: Parent->Child1->Child2 at least. Parent->Child1 should have already been resolved

    const std::string& startName = path.front()->name;
    const std::string& destName = path.back()->name;

    std::string currentName = startName;
    std::string nextName = path[1]->name; // lookahead to know whether we go to the parent or somewhere else

    Eigen::MatrixXcd AccumulatedForward;
    Eigen::MatrixXcd AccumulatedBackward;
    bool Initialised = false;
    // If i is the parent and mu is the new basis
    //|e_\mu} = L_\mu^{i} |e_i>. Expected to be stored as L_{i\mu}
    for (size_t it = 0; it < path.size(); it++)
    {

        if (path[it]->name != path[it]->parentName)
        {
            if (Initialised)
            {
                if (nextName == path[it]->parentName)
                {
                    AccumulatedForward = AccumulatedForward*path[it]->hereToParentDirect;
                    AccumulatedBackward = path[it]->parentToHereDirect*AccumulatedBackward;
                    currentName = nextName;
                    if (it < path.size()-2) // look at the element after the parent. The parent is next
                        nextName = path[it+2]->name;
                }
                else if (nextName == path[it]->name)
                {
                    AccumulatedForward = AccumulatedForward*path[it]->parentToHereDirect;
                    AccumulatedBackward = path[it]->hereToParentDirect*AccumulatedBackward;
                    currentName = nextName;
                    if (it < path.size()-1) // look at the next element
                        nextName = path[it+1]->name;
                }
                //If the node is a V shape i.e.      4 -> 1 -> 2
                //                                          -> 3
                //And the goal is to get from 3->2 then 3->1->2 is a valid path but when on 1. nextName = 2 =/= 1 =/= 4
            }
            else
            {
                if (nextName == path[it]->parentName)
                {
                    AccumulatedForward = path[it]->hereToParentDirect;
                    AccumulatedBackward = path[it]->parentToHereDirect;
                    currentName = nextName;
                    if (it < path.size()-2)
                        nextName = path[it+2]->name;
                    Initialised = true;
                }
                else if (nextName == path[it]->name)
                {
                    AccumulatedForward = path[it]->parentToHereDirect;
                    AccumulatedBackward = path[it]->hereToParentDirect;
                    currentName = nextName;
                    if (it < path.size()-1)
                        nextName = path[it+1]->name;
                    Initialised = true;
                }
            }
        }


    }
    releaseAssert(currentName == destName,"Path is Broken, not reached end");
    return addBasis(destName,startName,AccumulatedForward,true,&AccumulatedBackward).first;
}

struct BasisManager::Path
{
    std::vector<std::shared_ptr<BasisManager::Basis>> path;
    Path operator+(const std::shared_ptr<BasisManager::Basis>& newNode)
    {
        Path ret = *this;
        ret.path.push_back(newNode);
        return ret;
    }
};
//Find the path less the tags
std::vector<std::shared_ptr<BasisManager::Basis>> BasisManager::findPath(std::shared_ptr<Basis> start, const std::string from, const std::string to)
{
    Path resultantPath;
    std::shared_lock<std::shared_mutex> lock(m_basisLock);
    //No direct connection so must enumerate the graph

    // This is basically Dijsktra but we check if we have been to a node before.
    // This check can be eliminated by prestoring a list of visited nodes and the fastest ways to get to them but this requires the Node->vistedNodes lookup or a search.
    // Either way none of this will be a bottleneck
    std::list<Path> searchStack;
    searchStack.push_back({{start}});

    while (searchStack.size() > 0)
    {
        Path currentPath = searchStack.front();
        searchStack.pop_front();
        for (const auto& l : currentPath.path.back()->linkedNodes)
        {
            if (!l->isAutoGenerated && !contains(currentPath.path,l))
            {
                if (l->name == to)
                {
                    resultantPath = currentPath + l;
                    return resultantPath.path;
                }
                searchStack.push_back(currentPath + l);
            }
        }
    }

    return resultantPath.path;
}
std::vector<std::pair<std::string, std::string> > BasisManager::generateLinkElements(const std::string &fromInput, const std::string &toInput)
{
    //Generates the basic elements that must exist for the builtin basis objects.
    std::vector<std::pair<std::string, std::string> > ret;

    std::vector<possibleTags> tagsFrom = checkForTags(fromInput);
    std::vector<possibleTags> tagsTo = checkForTags(toInput);
    std::string sanitisedFrom = sanitizeInput(fromInput,true);
    std::string sanitisedTo = sanitizeInput(toInput,true);
    //TODO Lowdin Basis should be its own node so something like 1_LB_AAB should have 1_LB as its parent not 1
    if (tagsFrom.size() > 0)
    {
        ret.emplace_back(std::make_pair(sanitisedFrom,fromInput));
    }
    if (tagsTo.size() > 0)
    {
        ret.emplace_back(std::make_pair(sanitisedTo,toInput));
    }
    if (sanitisedFrom != sanitisedTo)
        ret.emplace_back(std::make_pair(sanitisedFrom,sanitisedTo));

    return ret;
}

std::shared_ptr<BasisManager::Basis> BasisManager::findLink(std::string fromInput, std::string toInput)
{
    //This function is not guaranteed to be atomic if it needs to add a transformation.
    //In principle if two people in different threads call this and cause it to generate a transformation,
    //the transformation could be added twice. If a transformation is added by this while another thread deletes it the parent basis link is a use after free.

    // Returns the element that links `from' and `to'. If it doesnt exist, generates it
    // Effectively this is a breadth first search through the graph.
    // The first pass checks if there are any direct connections between the given nodes. If so we choose that.
    // If not then autogenerated paths are ignored and a Breadth first search is conducted to find the path between the two nodes.
    // When adding a transformation to the graph it is checked that this path is impossible so there is only one unique path. I.e. the graph should be acyclic once the autogenerated edges have been removed

    auto linkNode = lookupBasis(fromInput,toInput,true); // linkNode links from and to. Or if from == to then linkNode has name == from
    if (linkNode)
    {
        return linkNode;
    }    

    std::vector<possibleTags> tagsFrom = checkForTags(fromInput);
    std::vector<possibleTags> tagsTo = checkForTags(toInput);
    std::string sanitisedFrom = sanitizeInput(fromInput,true);
    std::string sanitisedTo = sanitizeInput(toInput,true);
    if (!lookupBasis(sanitisedFrom,false))
    {
        // logger().log("Requested a transformation from a basis that does not exist",sanitisedFrom);
        return nullptr;
    }
    if (!lookupBasis(sanitisedTo,false))
    {
        // logger().log("Requested a transformation to a basis that does not exist",sanitisedTo);
        return nullptr;
    }

    //Try putting the tags in canonical order
    if (tagsFrom.size() > 0 || tagsTo.size() > 0)
    {
        std::sort(tagsFrom.begin(),tagsFrom.end());
        std::sort(tagsTo.begin(),tagsTo.end());
        std::string trialFrom = buildCanonicalBasisString(sanitisedFrom,tagsFrom);
        std::string trialTo = buildCanonicalBasisString(sanitisedTo,tagsTo);

        linkNode = lookupBasis(trialFrom,trialTo,true); // linkNode links from and to. Or if from == to then linkNode has name == from
        if (linkNode)
        {
            //Add an alias for this Basis for faster lookup
            addBasis(toInput,fromInput,linkNode->parentToHereDirect,true,&linkNode->hereToParentDirect);
            return linkNode;
        }
        //Will become cached next time with the correct name, This way all possible permutations will just use the cache
        fromInput = trialFrom;
        toInput = trialTo;
    }
    //Generates the special bases one by one

    std::vector<std::pair<std::string, std::string> > neededTransforms = generateLinkElements(fromInput,toInput);
    if (neededTransforms.size() > 1)
    {
        for (const auto& p : neededTransforms)
        {
            if (!findLink(p.first,p.second))
                return nullptr;
        }
    }
    else if (neededTransforms.size() == 1)
    {
        const auto& p = neededTransforms[0];
        if (p.first != fromInput)
        {
            assert(p.second != toInput);
            if (!findLink(p.first,p.second))
                return nullptr;
        }
        else
            assert(p.second == toInput);
    }
    else
        releaseAssert(false, "Unhandled case");




    linkNode = lookupBasis(fromInput,toInput,false); // linkNode links from and to. Or if from == to then linkNode has name == from
    if (linkNode)
        return linkNode;
    //If this failed this means we need to do a path search

    bool toInputExists = (bool)lookupBasis(toInput,false);
    bool fromInputExists = (bool)lookupBasis(fromInput,false);
    assert(fromInputExists); // I think this should always exist

    linkNode = lookupBasis(fromInput,toInputExists ? toInput : sanitisedTo,false); //direct connection


    std::shared_ptr<BasisManager::Basis> resultantBasis;
    if (!linkNode)
    { //No direct connection, Do the lookup
        std::vector<std::shared_ptr<Basis>> resultantPath;
        std::shared_ptr<Basis> start = lookupBasis(fromInput,false);
        if (!start)
            return nullptr;
        resultantPath = findPath(start,fromInput, toInputExists ? toInput : sanitisedTo);
        if (resultantPath.size() == 0)
        {
            //Could not find path
            return nullptr;
        }
        resultantBasis = generateDirectLinkAlongPath(resultantPath);
    }
    else
        resultantBasis = linkNode;
    if (toInputExists)
        return resultantBasis;

    //toInput does not exist so path is only until sanitisedTo

    std::shared_ptr<Basis> end = lookupBasis(sanitisedTo,false);
    if (!end)
        return nullptr;

    //It is assumed that the Tags commute. I.e. doing one first and then the other is the same as other other way around
    Eigen::MatrixXcd AccumulatedForward;
    if (resultantBasis->isOrthoNormal)
        AccumulatedForward = resultantBasis->loweringMetric;
    else if (fromInput == sanitisedTo)
    {
        AccumulatedForward = Eigen::MatrixXcd::Identity(resultantBasis->loweringMetric.cols(),resultantBasis->loweringMetric.cols());
    }
    else
    {
        if (resultantBasis->parentName == fromInput)
            AccumulatedForward = resultantBasis->parentToHereDirect;
        else
            AccumulatedForward = resultantBasis->hereToParentDirect;
    }
    Eigen::MatrixXcd AccumulatedBackward;
    if (resultantBasis->isOrthoNormal)
        AccumulatedBackward = resultantBasis->loweringMetric;
    else if (fromInput == sanitisedTo)
    {
        AccumulatedBackward = Eigen::MatrixXcd::Identity(resultantBasis->loweringMetric.cols(),resultantBasis->loweringMetric.cols());
    }
    else
    {
        if (resultantBasis->parentName == fromInput)
            AccumulatedBackward = resultantBasis->hereToParentDirect;
        else
            AccumulatedBackward = resultantBasis->parentToHereDirect;
    }

    for(const auto& t : tagsTo)
    {
        switch (t)
        {
        case possibleTags::LowdinBasis:
        {
            if (end->isProjection)
                return nullptr;// Cannot make Lowdin basis from a projection basis since the metric is inconsistent.
            Eigen::MatrixXcd LB = makeLowdin(end);
            AccumulatedForward *=  LB;
            LB = makeLowdinInverse(end);
            AccumulatedBackward =  LB * AccumulatedBackward ;
            break;
        }
        case possibleTags::ABlock:
        {
            Eigen::MatrixXcd AA = makeAlpha(end);
            AccumulatedForward *=  AA;
            AA = makeAlphaInv(end);
            AccumulatedBackward = AA *AccumulatedBackward;
            break;
        }
        case possibleTags::BBlock:
        {
            Eigen::MatrixXcd BB = makeBeta(end);
            AccumulatedForward *=  BB;
            BB = makeBetaInv(end);
            AccumulatedBackward = BB * AccumulatedBackward;
            break;
        }
        default:
            releaseAssert(false, "Not Implemented Switch case");
            break;
        }
    }
    /* Truth table
     * sanitisedFrom == sanitisedTo | sanitisedTo == toInput | sanitisedFrom == fromInput | isOneStep
     *               T              |             T          |               T            |   F --Not possible since this means fromInput == toInput and therefore we should have already found the basis and solved it
     *               T              |             T          |               F            |   T -- One step  fromInput->toInput
     *               T              |             F          |               T            |   T -- One step  fromInput->toInput
     *               T              |             F          |               F            |   F -- Two steps fromInput->sanitisedTo->toInput
     *               F              |             X          |               X            |   F -- At least two steps sanitisedFrom->sanitisedTo unless sanitisedTo == toInput && sanitisedFrom == fromInput and sanitisedFrom->sanitisedTo are neighbours
     */
    assert(fromInput != toInput);
    assert(!(lookupBasis(sanitisedFrom,sanitisedTo,false) && sanitisedTo == toInput && sanitisedFrom == fromInput)); // The last case

    bool isOneStep = sanitisedFrom == sanitisedTo && XOR(sanitisedTo == toInput,sanitisedFrom == fromInput);
    bool toInputisProjection = false; if (auto b = lookupBasis(toInput,false)) toInputisProjection = b->isProjection; // https://en.cppreference.com/w/cpp/language/if.html
    bool fromInputisProjection =false; if (auto b = lookupBasis(fromInput,false)) fromInputisProjection = b->isProjection;

    std::pair<std::shared_ptr<BasisManager::Basis>,std::unique_lock<std::shared_mutex>> bas;
    if (isOneStep && contains(tagsTo, possibleTags::LowdinBasis))
        bas = addOrthogonalBasis(toInput,fromInput,AccumulatedForward, false ,&AccumulatedBackward);
    else if (contains(tagsTo, possibleTags::LowdinBasis))
        bas = addOrthogonalBasis(toInput,fromInput,AccumulatedForward, true ,&AccumulatedBackward);
    else
        bas = addBasis(toInput,fromInput,AccumulatedForward,isOneStep ? false : true,&AccumulatedBackward);

    if (bas.first->isAutoGenerated)
        bas.first->isProjection = toInputisProjection; // we hold the lock so cant do any more lookups
    if (tagsTo.size() > 0) // autogenerated by us
        bas.first->isProjection = fromInputisProjection;
    return bas.first;
}


std::shared_ptr<BasisManager::Basis> BasisManager::lookupBasis(const std::string &inString, bool allowAutoGenerated)
{
    //O(n) which is fine
    std::string basisString = buildCanonicalBasisString(inString);
    std::shared_lock<std::shared_mutex> lock(m_basisLock);
    for (const auto& bas : m_BasisList)
    {
        if (!allowAutoGenerated && bas->isAutoGenerated)
            continue;
        if (bas->name == basisString)
            return bas;
    }
    return nullptr;
}

std::shared_ptr<BasisManager::Basis> BasisManager::lookupBasis(const std::string &fromIn, const std::string& toIn, bool allowAutoGenerated)
{
    //O(n) which is fine
    std::string from = buildCanonicalBasisString(fromIn);
    std::string to = buildCanonicalBasisString(toIn);
    std::shared_lock<std::shared_mutex> lock(m_basisLock);
    for (const auto& bas : m_BasisList)
    {
        if (!allowAutoGenerated && bas->isAutoGenerated)
            continue;
        if (bas->links(from,to))
            return bas;
    }
    return nullptr;
}


bool BasisManager::hasSpinBlockTag(const std::string &basisName)
{
    std::vector<possibleTags> tags = checkForTags(basisName);
    bool hasAATag = contains(tags,possibleTags::ABlock);
    bool hasBBTag = contains(tags,possibleTags::BBlock);
    releaseAssert(!(hasAATag && hasBBTag) ,"Matrix cannot have both tags");
    return hasAATag || hasBBTag;
}

