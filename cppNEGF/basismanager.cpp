BasisManager::BasisTransform<Eigen::MatrixXcd> BasisManager::getTransform(const std::string &from, enums::IndexType fromIndex, const std::string &to, enums::IndexType toIndex,  bool AllowProjectedRaising)
{

    //Special case the eigenValue type and the invalid type
    if (fromIndex == toIndex && (fromIndex == enums::IndexType::eigenValue || fromIndex == enums::IndexType::invalid))
    {
        //This index does not need to be transformed
        return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),true};
    }
    if (fromIndex == toIndex && from == to)
    {
        //This index does not need to be transformed
        return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),true};
    }
    std::shared_ptr<Basis> bas = findLink(from,to);
    if (!bas) return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};

    std::shared_ptr<Basis> basTo = lookupBasis(to,false);
    if (!basTo) return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
    // If allow projectedRaising then this is not an error. It can be well defined to do this if your aim is to insert an overlap matrix between indexes being contracted.
    // e.g. v^\bar{i} S_{\bar{i}j}v^j vs v_j v^j where v_j = v^\bar{i} S_{\bar{i}j} with all indexes summing over the reduced basis set.
    if (basTo->isProjection && fromIndex != toIndex && !AllowProjectedRaising)
    {
        //If the from basis is not a projection than this error can be recovered by transforming the index first and then projecting.
        std::shared_ptr<Basis> basFrom = lookupBasis(from,false);
        if (!basFrom) return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
        if (basFrom->isProjection)
            // Could be recovered if this is a tree like transformation that goes through a full basis intermediate, Too complicated right now, Do it in two steps
        {
            //Nice error message
            logger().log("Could not convert indices in basis", from);
            logger().log("fromIndex", fromIndex);
            logger().log("toIndex", toIndex);
            return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
        }

        //basFrom is not a projection. Construct the transformation in two parts.
        BasisTransform<Eigen::MatrixXcd> transformationPart1 = getTransform(from,fromIndex,from,toIndex,AllowProjectedRaising);
        BasisTransform<Eigen::MatrixXcd> transformationPart2 = getTransform(from,toIndex,to,toIndex,AllowProjectedRaising);
        if (!transformationPart1 || !transformationPart2)
            return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
        if (transformationPart1.isIdentity)
            return transformationPart2;
        else if (transformationPart2.isIdentity)
            return transformationPart1;
        else
        {
            *transformationPart1 *= *transformationPart2;
            return transformationPart1;
        }

    }
    // If i is the old and mu is the new basis
    //|e_\mu} = L_\mu^{i} |e_i>. Stored as L_{i\mu}
    //Therefore a direct basis object is transformed by multiplication on the right!
    BasisTransform<Eigen::MatrixXcd> transformation;
    if (from != to)
    {
        //Having to and from backwards means we need the inverse transform.
        //Transforming a dual basis object also means we need the inverse transform
        //Therefore two inverses make a not inverse. I.e. XOR
        bool InverseTransform = to == bas->parentName;
        bool DualTransform = fromIndex == enums::IndexType::dual || fromIndex == enums::IndexType::improperDual;
        bool isEigenValueOrInvalid = fromIndex == enums::IndexType::eigenValue || fromIndex == enums::IndexType::invalid;

        if (InverseTransform && DualTransform)
            transformation.transform.get() = bas->parentToHereDirect.transpose();
        else if (InverseTransform && !DualTransform)
            transformation.transform.get() = bas->hereToParentDirect;
        else if (!InverseTransform && DualTransform)
            transformation.transform.get() = bas->hereToParentDirect.transpose();
        else if (!InverseTransform && !DualTransform)
            transformation.transform.get() = bas->parentToHereDirect;
        else if (isEigenValueOrInvalid) // This is the case if the index == eigenvalue or invalid
            transformation.isIdentity = true;//Never reached
        else
            releaseAssert(false, "Unhandled case");
    }
    else
    {
        transformation.isIdentity = true;
    }
    //The overall order would be something like SLS^{-1} but L is identity so this simplifies
    if (fromIndex == toIndex && transformation.isIdentity)
        return transformation;
    if (!transformation.isIdentity)
    {
        switch (fromIndex)
        {
        case enums::IndexType::direct:// Default case
        case enums::IndexType::dual://Handled already when deciding on the transform to use.
            break;
        case enums::IndexType::improperDirect:
        case enums::IndexType::improperDual:
            //Need to take the conjugate
            transformation.transform.get() = transformation.transform.get().conjugate();
            break;
        case enums::IndexType::eigenValue:
        case enums::IndexType::invalid:
            break;
        default:
            releaseAssert(false,"Unhandled switch case");
        }
        if (fromIndex == toIndex)
            return transformation; // No metrics needed
    }

    //From index != toIndex
    //S_{\bar{i}j} S^{i\bar{j}}
    bas = lookupBasis(to,false); // we care about the properties of the to basis now. This != bas potentially. E.g. it is the parent basis
    if (!bas)
        return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
    if (bas->isOrthoNormal)
    {
        if (transformation.isIdentity)
            //Not needed to construct an empty transformation but it will give errors later if someone ignores the identity tag
            return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),true};
        else
            return transformation;
    }

    //Not orthonormal
    if (fromIndex == enums::IndexType::direct && toIndex == enums::IndexType::improperDual)
    {    
        if (transformation.isIdentity)
        {
            transformation.transform.get() = bas->raisingMetric;
            transformation.isIdentity = false;
            return transformation;
        }
        else
        {
            BasisTransform<Eigen::MatrixXcd> temp;
            temp.transform->noalias() = transformation.transform.get()*bas->raisingMetric;
            return temp;
        }
    }
    else if (fromIndex == enums::IndexType::improperDual && toIndex == enums::IndexType::direct)
    {
        if (transformation.isIdentity)
        {
            transformation.transform.get() = bas->loweringMetric;
            transformation.isIdentity = false;
            return transformation;
        }
        else
        {
            BasisTransform<Eigen::MatrixXcd> temp;
            temp.transform->noalias() = transformation.transform.get()*bas->loweringMetric;
            return temp;
        }
    }
    else if (fromIndex == enums::IndexType::dual && toIndex == enums::IndexType::improperDirect)
    {
        if (transformation.isIdentity)
        {
            transformation.transform.get() = bas->loweringMetric.transpose();
            transformation.isIdentity = false;
            return transformation;
        }
        else
        {
            BasisTransform<Eigen::MatrixXcd> temp;
            temp.transform->noalias() = transformation.transform.get()*bas->loweringMetric.transpose();
            return temp;
        }
    }
    else if (fromIndex == enums::IndexType::improperDirect && toIndex == enums::IndexType::dual)
    {
        if (transformation.isIdentity)
        {
            transformation.transform.get() = bas->raisingMetric.transpose();
            transformation.isIdentity = false;
            return transformation;
        }
        else
        {
            BasisTransform<Eigen::MatrixXcd> temp;
            temp.transform->noalias() = transformation.transform.get()*bas->raisingMetric.transpose();
            return temp;
        }
    }
    else
    {
        logger().log("Unhandled index transform case");
        return BasisTransform<Eigen::MatrixXcd> {MatrixBufferObject<Eigen::MatrixXcd>::getEmpty(),false};
    }
}

BasisManager::BasisTransform<Eigen::SparseMatrix<complexType>> BasisManager::getTransform_S(const std::string &from, enums::IndexType fromIndex, const std::string &to, enums::IndexType toIndex,  bool AllowProjectedRaising)
{
    BasisTransform<Eigen::MatrixXcd> denseTransform = getTransform(from,fromIndex,to,toIndex,AllowProjectedRaising);
    if (!denseTransform)
        return BasisTransform<Eigen::SparseMatrix<complexType>> {MatrixBufferObject<Eigen::SparseMatrix<complexType>>::getEmpty(),false};
    if (denseTransform.isIdentity)
        return BasisTransform<Eigen::SparseMatrix<complexType>> {MatrixBufferObject<Eigen::SparseMatrix<complexType>>::getEmpty(),true};

    BasisTransform<Eigen::SparseMatrix<complexType>> temp;
    temp.transform.get() = denseTransform.transform->sparseView();
    temp.isIdentity = false; // Not needed
    return temp;
}



void BasisManager::addBasis(std::string name, const Eigen::MatrixXcd &loweringMetric)
{
    //New basis with no links
    name = sanitizeInput(name);
    auto foundBas = lookupBasis(name,true);
    if (foundBas)
    {
        logger().log("Basis already exists, not adding", name);
        return;
    }
    if constexpr(traceBasisCreations)
        logger().log("Creating basis from metric with name", name);

    auto bas = std::make_shared<Basis>();
    bas->name = name;
    bas->parentName = name;
    bas->loweringMetric = loweringMetric;
    bas->raisingMetric = loweringMetric.inverse();//TODO be clever about zeros
    std::unique_lock<std::shared_mutex> lock(m_basisLock);
    BasisManager::getInstance().m_BasisList.emplace_back(std::move(bas));
}

