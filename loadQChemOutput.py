def figureOutPermutation(hcoreQchem, hcoreOther, tolerance = 1e-6):
    #Figures out how to permute the rows and columns of hcoreQchem to get hcoreOther, if possible
    permuteMatrix = np.identity(len(hcoreOther))
    hcoreQchemPermuted = hcoreQchem
    toBreak = True
    while toBreak:# GOTOs dont exist even though this would be a good time for one
        toBreak = False
        for rowQchem,rowOther in zip(hcoreQchemPermuted,hcoreOther):
            for idxOther,elemOther in enumerate(rowOther):
                if not np.isclose(elemOther,rowQchem[idxOther],rtol=tolerance):
                    #Not the same so find its pair
                    foundPair = False
                    idxs = np.where(np.isclose(rowQchem[idxOther:], elemOther,rtol=tolerance))[0]
                    if len(idxs) > 0:
                        idx = idxs[0]+idxOther
                        foundPair = True
                    assert(foundPair)
                    qchemIndex1 = np.where(permuteMatrix[:,idx] == 1)[0][0]
                    qchemIndex2 = np.where(permuteMatrix[:,idxOther] == 1)[0][0]
                    permuteMatrix[qchemIndex1,idxOther] = 1
                    permuteMatrix[qchemIndex2,idxOther] = 0
                    permuteMatrix[qchemIndex1,idx] = 0
                    permuteMatrix[qchemIndex2,idx] = 1
                    print(f"Element: {elemOther} at {idxOther} did not match {rowQchem[idxOther]}, Instead this is at {idx}")
                    print(f"Matrix now has ({qchemIndex1},{idxOther}) and ({qchemIndex2},{idx})")
                    #Applies the swap to the permutation matrix
                    toBreak = True
                if toBreak:
                    break
            if toBreak:
                    break
        hcoreQchemPermuted = permuteMatrix @ hcoreQchem @ permuteMatrix
    print("Succesfully aligned the two matrices")
    assert(np.allclose(hcoreQchemPermuted,hcoreOther,rtol=tolerance))
    return permuteMatrix

