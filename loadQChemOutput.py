def generatePyscfAtomString(fchkParams):
    atomstring = ""
    
    for atomicNumber,Pos in zip(fchkParams["AtomicNumbers"],fchkParams["CartCoords"]):
        atomstring += f"{TABLE_OF_ELEMENTS[atomicNumber]} {Pos[0]*BohrInAngstrom} {Pos[1]*BohrInAngstrom} {Pos[2]*BohrInAngstrom};"
    return atomstring

def loadWithRevQCMagic(outputName):
    """Returns a density matrix for use as an initial guess and a configured pySCF mol from the qchem file"""
    from qcmagic.interfaces.converters.qchem import qchem_output_to_configuration_state
    from qcmagic.interfaces.converters.pyscf import configuration_to_mol
    from qcmagic.core.cspace.basis.basisshell import BasisType
    from qcmagic.core.sspace.single_determinant import SingleDeterminant

    config, state = qchem_output_to_configuration_state(outputName+".out",0.0)
    cbs = config.get_subconfiguration("ConvolvedBasisSet")
    libintOccMOs = state.occupied_coefficients
    pyscfOccMOs=  cbs.convert_coefficient_matrices(
        libintOccMOs, BasisType.BT_LIBINT, BasisType.BT_PYSCF
    )
    pyscfState = SingleDeterminant(state.n_electrons, config, holo = False,
                                    occ_coeffs = pyscfOccMOs)
    pyscfMol = configuration_to_mol(config)
    #Need to set the ECP correctly
    fchkParams = loadFCHK(outputName + ".fchk")
    if "ECPMatrix" in fchkParams:
        pyscfMol.ecp = fchkParams["Basis"]
        pyscfMol.build()
    return (pyscfState.density_matrices[0],pyscfMol)
