LoweringMetric BasisManager::getMetric(const std::string &basis)
{
    auto bas = lookupBasis(basis,true);//Metric is the same even if it is autogenerated
    if (!bas)
        return LoweringMetric();
    return LoweringMetric(bas->loweringMetric,basis,enums::SpinSymmetry::NoSpinSym);
}

bool BasisManager::isOrthogonal(const std::string &basis)
{
    auto bas = lookupBasis(basis,true);
    if (!bas)
        return false;
    return bas->isOrthoNormal;
}

void BasisManager::deleteBasis(const std::string &name)
{
    if (name == "")
    {
        logger().log("Cannot delete Null Basis");
        return;
    }
    auto& bm = getInstance();
    std::unique_lock<std::shared_mutex> lock(bm.m_basisLock);
    for (auto it = bm.m_BasisList.begin(); it != bm.m_BasisList.end(); )
    {
        if (sanitizeInput((*it)->name,true) == name)
        {
            lock = (*it)->cleanupMyself(std::move(lock));
            it = bm.m_BasisList.erase(it);
        }
        else
            ++it;
    }
}

void BasisManager::deleteAllBasis()
{
    auto& bm = getInstance();
    {
        std::unique_lock<std::shared_mutex> lock(bm.m_basisLock);
        for (const auto& bas : bm.m_BasisList)
        {
            lock = bas->cleanupAll(std::move(lock));
        }
        bm.m_BasisList.clear();
    }
    bm.makeNullBasis();
}

std::string BasisManager::buildCanonicalBasisString(std::string basis, std::vector<possibleTags> tags)
{
    std::sort(tags.begin(),tags.end());
    std::string canonical = sanitizeInput(basis,true); // This way it can be used to change the tags on a basis
    bool foundLowdin = false;
    bool foundBlock = false;
    for (const auto& t : tags)
    {
        switch (t)
        {
        case possibleTags::LowdinBasis:
            canonical += LowdinOrthogonaliseBasis;
            if (foundLowdin) {logger().log("Duplicate Lowdin basis tag"); return "";}
            foundLowdin = true;
            continue;
        case possibleTags::ABlock:
            canonical += Alpha_Block;
            if (foundBlock) {logger().log("Duplicate SpinBlock tag"); return "";}
            foundBlock = true;
            continue;
        case possibleTags::BBlock:
            canonical += Beta_Block;
            if (foundBlock) {logger().log("Duplicate SpinBlock tag"); return "";}
            foundBlock = true;
            continue;
        case possibleTags::NullBasis:
            continue;
        default:
            releaseAssert(false, "Unhandled Switch case");
        }
    }
    return canonical;
}

std::string BasisManager::buildCanonicalBasisString(std::string basis)
{
    std::vector<possibleTags> tags = checkForTags(basis);
    if (tags.size() == 0)
        return basis;
    basis = sanitizeInput(basis,true);
    return buildCanonicalBasisString(basis,tags);
}

std::string BasisManager::removeSpinTags(std::string basis, possibleTags* deletedTag)
{
    std::vector<possibleTags> tags = checkForTags(basis);
    if (tags.size() == 0)
        return basis;
    for (auto it = tags.begin(); it != tags.end();)
    {
        switch (*it)
        {
        case possibleTags::ABlock:
        case possibleTags::BBlock:
            if (deletedTag) *deletedTag = *it;
            it = tags.erase(it);
            continue;
        default:
            ++it;
            continue;
        }
    }
    basis = sanitizeInput(basis,true);
    return buildCanonicalBasisString(basis,tags);
}












