def loadTextMatrix(filename):
    with open(filename, 'r') as file:
        matrix = []
        for line in file:
            row = [float(value) for value in line.strip().split() if value]
            matrix.append(row)
        return np.array(matrix)

def loadBinary2Eri(filename,NBasis):
    # loads a file called XXX2eri.bin aka file 21.0 in qchem. 
    # This is generated by the SAVE_AO_INTEGRALS 1 rem setting
    # ln -s QChemNEGF/3-MCHO/h2_Test/scratch/h2/21.0 H22eri.bin
    try:
        eri = np.fromfile(filename,dtype=np.float64)
        eriLength = len(eri)
        eriReshapeLength = int(eriLength**0.25)
        if eriLength != eriReshapeLength*eriReshapeLength*eriReshapeLength*eriReshapeLength:
            eriReshapeLength +=1 #rounding
        if eriLength != eriReshapeLength*eriReshapeLength*eriReshapeLength*eriReshapeLength:
            eriReshapeLength -=2 #rounding
        if eriLength != eriReshapeLength*eriReshapeLength*eriReshapeLength*eriReshapeLength:
            return np.zeros(shape=(0,0))
        #assert(eriLength == eriReshapeLength*eriReshapeLength*eriReshapeLength*eriReshapeLength)

        eri = eri[:eriReshapeLength*eriReshapeLength*eriReshapeLength*eriReshapeLength].reshape((eriReshapeLength*eriReshapeLength,eriReshapeLength*eriReshapeLength))
    except FileNotFoundError as e:
        print(f"Could not open file: {filename}")
        return np.zeros(shape=(0,0))
    return eri

def load1EInt(filename):
    # loads a file called XXX1eInt.dat aka file NEGF_hmat.tmp in qchem. 
    # This is generated by NEGF with a modified code to generate even in analysis mode line 2089 in scfman.C 
    # ln -s QChemNEGF/3-MCHO/h2_Test/scratch/h2/NEGF_hmat.tmp H21eInt.bin
    mat = loadTextMatrix(filename).flatten()
    length = len(mat)
    squareLength = int(length**0.5)
    if length != squareLength*squareLength:
        squareLength += 1
    if length != squareLength*squareLength:
        squareLength -= 2
    assert(length == squareLength*squareLength)
    return mat.reshape(squareLength,squareLength)

def loadVector(file,typeCast,N):
    #Assumes that reading to the end of the line wont go over N, i.e the vector is terminated by a new line
    matrix = []
    for line in file:
        row = [typeCast(value) for value in line.strip().split() if value]
        matrix += row
        if len(matrix) >= N:
            break
    if len(matrix) > N:
        print(f"Overread matrix?, Len:{len(matrix)}, N:{N}")
    return np.array(matrix)

def makeSquareFromLT(mat,NBasis):
    #Makes a square matrix from a lower triangular vectoriesed one
    hcoreVectorIter = iter(mat)
    ret = np.zeros(shape=(NBasis,NBasis)) # For now these are always real
    for i in range(NBasis):
        for j in range(i+1):
            ret[i,j] = next(hcoreVectorIter)
            ret[j,i] = ret[i,j]

    return ret





def loadFCHK(filename):
    #Parses a file called XX.fchk from QCHEM e.g.
    #ln -s QChemNEGF/3-MCHO/h2_Test/h2.in.fchk H2.fchk
    #In principle this can parse any FCHK file

    

    #Main Parsing function
    Params = {}
    with open(filename, 'r') as file:
        Params["Comment"] = next(file).rstrip()
        Params["Basis"] = next(file).split()[-1].rstrip()
        for line in file:
            
            for TagName, TagString in FCHK_TAGS.items():
                if line.startswith(TagString):
                    if "N=" in line:
                        #Vector
                        n_match = re.search(r"N=\s*(\d+)", line)
                        if n_match:
                            n = int(n_match.group(1))
                            if "R" in line.split():
                                Params[TagName] = loadVector(file,float,n)
                            elif "I" in line.split():
                                Params[TagName] = loadVector(file,int,n)
                            else:
                                print(f"Unknown Array dataType in {TagString}")
                        else: 
                            print(f"Identified {TagString} as a vector but couldnt determine size")
                    else:
                        #Not a vector
                        splitLine = line.split()
                        if "I" in splitLine:
                            #Integer
                            IIndex = splitLine.index("I")
                            Params[TagName] = int(splitLine[IIndex+1])
                        elif "R" in splitLine:
                            #Real number
                            RIndex = splitLine.index("R")
                            Params[TagName] = float(splitLine[RIndex+1])
                        else:
                            print(f"Unknown dataType in {TagString}")

    #Some cleanup needed
    if not "BetaMoCoeff" in Params:
        Params["BetaMoCoeff"] = Params["AlphaMoCoeff"]
    
    #Make HCore square
    # hcoreVector = Params["HCore"]
    # hcoreVectorIter = iter(hcoreVector)
    # NBasis = Params["NBasis"]
    # Params["HCore"] = np.zeros(shape=(NBasis,NBasis)) # For now these are always real
    # for i in range(NBasis):
    #     for j in range(i+1):
    #         Params["HCore"][i,j] = next(hcoreVectorIter)
    #         Params["HCore"][j,i] = Params["HCore"][i,j]
    Params["HCore"] = makeSquareFromLT(Params["HCore"],Params["NBasis"])
    if "ECPMatrix" in Params:
        Params["ECPMatrix"] = makeSquareFromLT(Params["ECPMatrix"],Params["NBasis"])
    #Reshape Atomic coords
    Params["CartCoords"] = Params["CartCoords"].reshape((-1,3))
    return Params

