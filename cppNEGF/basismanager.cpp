inline bool XOR(bool a, bool b)
{
    /* Truth table
     * A | B | Result
     * T | T | F
     * T | F | T
     * F | T | T
     * T | T | F
     */
    return a != b;
}
struct BasisManager::Basis
{
    //Identitification
    std::string name;
    std::string parentName; // If parent == name then there is no parent

    //Graph structure
    std::list<std::shared_ptr<Basis>> linkedNodes; //Other Nodes that can be transformed to

    //Basis details
    Eigen::MatrixXcd loweringMetric;
    Eigen::MatrixXcd raisingMetric;
    // If i is the parent and mu is the new basis
    // bas->parentToHereDirect = |e_\mu} = L_\mu^{i} |e_i>. Expected to be stored as L_{i\mu}
    Eigen::MatrixXcd parentToHereDirect;
    //If parentToHereDirect is square then this is the inverse of that matrix.
    //If not then it is such that L^{i}_{\mu}L^{\nu}_{i} = \delta_{\mu}^{\nu}. Note that \mu may have different number of indices than i
    // Eigen::MatrixXcd parentToHereDual; // L^{\nu}_{i} stored as L_{i \nu} // NOTE THIS IS DIFFERENT TO CONVENTION

    // bas->hereToParentDirect = |e_i} = L_i^{\mu} |e_\mu>. Stored as L_{\mu i}
    Eigen::MatrixXcd hereToParentDirect;
    //If parentToHereDirect is square then this is the inverse of that matrix.
    //If not then it is such that L^{i}_{\mu}L^{\mu}_{j} = \delta_{j}^{i}. Note that \mu may have different number of indices than \mu.
    // Eigen::MatrixXcd hereToParentDual;//L^{i}_{\mu} stored as L_{\mu i} // NOTE THIS IS DIFFERENT TO CONVENTION

    //If i has more indices than mu then \delta_{\mu}^{\nu} is the Identity matrix. However \delta_{j}^{i} Is a 'partial' Identity matrix with the same number of ones.

    bool isOrthoNormal = false; // Under conventional complex inner product
    bool isAutoGenerated = false; // Describes that this node has been generated to shortcut a basis transformation. It may also be a tagged node

    /* Projections in non-orthogonal bases have bad properties. For example AO->Mol0->Raise->AO =/= AO->Raise.
     * This is because the raising and lowering metric of the projected space are not inverses of one another
     * For a projection therefore we disable transformation of indices via the metric. Therefore things like the adjoint aren't allowed.
     * If the projection commutes with the metric, E.g. Lowdin basis, then there is no need to tag it as a projection.
     * We try to detect this and issue a warning if a projection is not marked as such when it should be
     */
    bool isProjection = false;

    //Utility function that constructs parentToHereDirect .. etc from parentToHereDirect. If parentToHereDirect is not invertible a warning will be issued.
    //Ideally we'd want to reduce the apparent dimension of the basis. This cant be done however since we must preserve the desired basis vectors.
    //This can lead to zeros in Eigenvalues computed in this basis etc. all this stemming from the fact that the basis has a null space
    /* As an example Consider the transformation
     * [[1,1],
     *  [1,1]]*0.5
     * The vector [[1],[1]] gets mapped to [[1],[1]]. But [[1],[-1]] gets mapped to [[0],[0]]. Therefore this transformation is not invertible
     * We could change the matrix to be
     * [[1,1]]*0.5 this would map [[1],[1]] to [[1]] and [[1],[-1]] gets mapped to [[0]]. This correctly conveys the dimensionality of the space but is a different transformation
     */

    static void generateTransformations(Eigen::MatrixXcd& parentToHereDirect/*, Eigen::MatrixXcd& parentToHereDual */,Eigen::MatrixXcd& hereToParentDirect/*, Eigen::MatrixXcd& hereToParentDual*/)
    {//                                                   n*p matrix. m = min(n,p)
        long m = std::min(parentToHereDirect.rows(), parentToHereDirect.cols());

        Eigen::BDCSVD<Eigen::MatrixXcd> SVD(parentToHereDirect, Eigen::ComputeThinU | Eigen::ComputeThinV);

        const Eigen::MatrixXcd& U = SVD.matrixU(); //Old x singular
        const Eigen::MatrixXcd& V = SVD.matrixV(); //new x singular
        //Sorted in decreasing order
        Eigen::VectorXd S = SVD.singularValues(); // singular x singular
        Eigen::VectorXd SInv = SVD.singularValues().cwiseInverse(); // singular x singular
        if (SVD.rank() != m)
        {
            logger().printf("Transformation has misleading dimension. Consider providing a non square transformation. Rank %li, at most %li\n",SVD.rank(),m);
            for (Eigen::Index sIdx = SVD.rank(); sIdx < SInv.rows(); ++sIdx)
            {
                SInv(sIdx) = 0;
            }
        }

        parentToHereDirect = U * S.asDiagonal() * V.adjoint(); // L^{i}_{\mu} as L_{i\mu}
        hereToParentDirect = V * SInv.asDiagonal() * U.adjoint(); // L^{\mu}_{i} as L_{\mu i}
        Eigen::MatrixXcd shouldBeID = parentToHereDirect*hereToParentDirect;
        Eigen::MatrixXcd shouldBeID2 = hereToParentDirect*parentToHereDirect;
        Eigen::MatrixXcd shouldBeID3 = V.adjoint()*V;
        Eigen::MatrixXcd shouldBeID4 = S.asDiagonal() * V.adjoint() * V * SInv.asDiagonal();
        Eigen::MatrixXcd shouldBeID5 = U*U.adjoint();
        Eigen::MatrixXcd shouldBeID6 = U * S.asDiagonal() * V.adjoint() * V * SInv.asDiagonal() * U.adjoint();
        return;
        // parentToHereDual =  hereToParentDirect.transpose(); // L^{\nu}_{i} as L_{i \nu}
        // hereToParentDual = parentToHereDirect.transpose(); // L^{i}_{\mu} as L_{\mu i}

        //Note that:
        //parentToHereDirect.transpose() * parentToHereDual = V.conjugate() * S.asDiagonal() * U.transpose() * U.conjugate() * S.cwiseInverse().asDiagonal() * V.transpose = I



    }

    Basis()
    {
#ifdef TRACEBASISDELETIONS
        ++numberOfObjects;
#endif
    }
    ~Basis()
    {
#ifdef TRACEBASISDELETIONS
        --numberOfObjects;
#endif
    }
    Basis(const Basis& other) = delete;
    Basis(Basis&& other) = default;
    Basis& operator=(const Basis& other) = delete;
    Basis& operator=(Basis&& other) = default;

    std::unique_lock<std::shared_mutex> removeNode(std::unique_lock<std::shared_mutex>&& lock, const std::string& nodeName)
    {
        for (auto l = linkedNodes.begin(); l != linkedNodes.end();)
        {
            if ((*l)->name == nodeName)
                l = linkedNodes.erase(l);
            else
                ++l;
        }
        if (parentName == nodeName)
            parentName = name;
        return std::move(lock);
    }

    std::unique_lock<std::shared_mutex> cleanupMyself(std::unique_lock<std::shared_mutex>&& lock)
    {
        //Remove this from all linked nodes.
        //What to do about dangling parentNames? On the one hand it is useful since the parent->Here transform is not invalidated if parent is deleted.
        //On the other hand the Here->Parent transform probably should be since the Parent metric may not be known anymore
        //If there are no more nodes with the parent Name then we must remove the parent and invalidate the transform.
         // modifying the graph so need a unique lock
        for (auto l = linkedNodes.begin(); l != linkedNodes.end();l++)
        {
            lock = (*l)->removeNode(std::move(lock),name);
        }
        linkedNodes.clear();
        return std::move(lock);

    }
    std::unique_lock<std::shared_mutex> cleanupAll(std::unique_lock<std::shared_mutex>&& lock)
    {//Removes all my children and deletes the reference to the parent. Use only when the entire graph will be cleared
        linkedNodes.clear();
        return std::move(lock);
    }

    bool operator ==(const Basis& other) const
    {
        return name == other.name && parentName == other.parentName;
    }

    bool links(const std::string& A, const std::string& B)
    {
        if (A == B && A == name)
            return true;
        if (A == name && B == parentName)
            return true;
        if (B == name && A == parentName)
            return true;
        return false;
    }

};




std::vector<BasisManager::possibleTags> BasisManager::checkForTags(std::string basisString, bool* success/* = nullptr*/)
{

    std::vector<possibleTags> listOfTags;
    if (success)
        *success = true;

    bool foundSpinBlockTag = false;
    bool foundLBTag = false;

    size_t foundLoc;

    while((foundLoc = basisString.find(LowdinOrthogonaliseBasis)) != std::string::npos)
    {
        if (foundLBTag && success)
            *success = false;
        foundLBTag = true;
        basisString.erase(foundLoc,LowdinOrthogonaliseBasis.size());
        listOfTags.push_back(possibleTags::LowdinBasis);
    }


    while ((foundLoc = basisString.find(Alpha_Block)) != std::string::npos)
    {
        if (foundSpinBlockTag && success)
            *success = false;
        foundSpinBlockTag = true;
        basisString.erase(foundLoc,Alpha_Block.size());
        listOfTags.push_back(possibleTags::ABlock);
    }

    while ((foundLoc = basisString.find(Beta_Block)) != std::string::npos)
    {
        if (foundSpinBlockTag && success)
            *success = false;
        foundSpinBlockTag = true;
        basisString.erase(foundLoc,Beta_Block.size());
        listOfTags.push_back(possibleTags::BBlock);
    }

    return listOfTags;
}

